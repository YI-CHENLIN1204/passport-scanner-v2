import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source = readFileSync('src/services/paddleOcr.ts', 'utf8')
const pixelStart = source.indexOf('async function createPixelCrop(')
const nameStart = source.indexOf('async function createTaiwanNameFieldCrop(', pixelStart)
const relativeStart = source.indexOf('async function createRelativeCrop(', nameStart)
const vizStart = source.indexOf('async function createTaiwanVizCrop(', relativeStart)
const bottomStart = source.indexOf('async function createBottomCrop(', vizStart)
assert.ok(pixelStart >= 0 && nameStart > pixelStart && relativeStart > nameStart && vizStart > relativeStart && bottomStart > vizStart)
const pixel = source.slice(pixelStart, nameStart)
const name = source.slice(nameStart, relativeStart)
const viz = source.slice(vizStart, bottomStart)
assert.match(pixel, /highQualityUpscale = false/)
assert.match(pixel, /if \(highQualityUpscale && scale > 1\)/)
assert.match(pixel, /context\.imageSmoothingQuality = 'high'/)
assert.match(name, /1400,\s*true,\s*\)/)
assert.match(viz, /1500,\s*true,\s*\)/)
assert.match(source, /OCR_PIPELINE_VERSION\s*=\s*'2026\.10\.11\.29'/)
assert.doesNotMatch(source, /async function createTaiwanFocusedVizCrop\(/)
console.log('Passport .29 quality resize is opt-in for existing name crops only')
