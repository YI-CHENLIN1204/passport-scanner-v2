import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const service = readFileSync('src/services/experimentalServerRecognition.ts','utf8')
const page = readFileSync('src/views/OcrQualityPage.vue','utf8')
const downloader = readFileSync('scripts/download-official-ocr-server-model.mjs','utf8')
const prepare = readFileSync('scripts/prepare-ocr-server-model.mjs','utf8')
const main = readFileSync('src/services/paddleOcr.ts','utf8')
const ignored = readFileSync('../.gitignore','utf8')

assert.match(service,/smokeTestServerRecognition/)
assert.match(service,/syntheticImage\(\)/)
assert.match(service,/canvas\.toBlob/)
assert.match(service,/new File\(\[blob\], 'synthetic-server-recognition.png'/)
assert.match(service,/textRecognitionModelAsset: \{ url: modelUrl \}/)
assert.match(service,/textDetectionModelName: 'PP-OCRv5_mobile_det'/)
assert.match(service,/await instance\.dispose\(\)/)
assert.match(service, /Array\.isArray\(obj\?\.items\)/)
assert.match(service, /recognizedSyntheticText: texts\.join/)
assert.match(page, /result\.recognizedSyntheticText/)
assert.doesNotMatch(service, /obj\?\.rec_texts/)

assert.match(service,/return await execute\('auto', false\)/)
assert.match(service,/return execute\('wasm', true\)/)
assert.match(service,/backend: 'wasm', numThreads: 1, wasmPaths: '\/ort-wasm\/'/)
assert.match(service, /message\.includes\('ceil_mode'\)/)
assert.match(service, /message\.includes\('WebGPU MaxPool'\)/)
const actualWebGpuError = 'ceil_mode output-shape is computed, but ceil_mode kernel execution (padding) is not yet implemented in the WebGPU MaxPool kernel'
const shouldFallback = (message) => message.includes('ceil_mode') && message.includes('WebGPU MaxPool')
assert.equal(shouldFallback(actualWebGpuError), true)
assert.equal(shouldFallback('model archive missing'), false)
assert.equal(shouldFallback('random WebGPU failure'), false)
assert.match(page,/result\.webgpuFallback/)

assert.match(page,/runServerModelSmoke/)
assert.match(page,/執行合成圖模型啟動測試/)
assert.match(downloader,/expectedOnnxSha='d9dc333c9c7b042c6dffb8e33d72b6f65c9c1d463d0a3c2f78174fea55e94752'/)
assert.match(prepare,/server-rec-manifest\.json/)
assert.match(ignored,/frontend\/public\/paddle-models\/experiments\//)
assert.match(main,/OCR_PIPELINE_VERSION\s*=\s*'2026\.10\.11\.29'/)
assert.doesNotMatch(main,/smokeTestServerRecognition/)
console.log('Server-rec smoke is opt-in and synthetic-only; production remains unchanged')
